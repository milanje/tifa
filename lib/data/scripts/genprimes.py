SOURCE = """\
{license}
/**
 * \\file    {name_src}
 * \\author  Automatically generated by {name_prog}
 * \\date    {date}
 * \\version {version}
 */

#include "{name_inc}"

const uint32_t first_primes[NFIRST_PRIMES] MAYBE_UNUSED = {{
{rows}
}};

const uint32_t LARGEST_PRIME MAYBE_UNUSED = {largest};

//
// _NOTE_: first_primes_array is merely an uint32_array_t wrapper for
//         first_primes, and as such, it has no real "alloced" memory.
//         Setting first_primes_array.alloced to 0 will prevent errors
//         if free_uint32_array is called on first_primes_array.
//
const uint32_array_t first_primes_array MAYBE_UNUSED = {{
    .alloced = 0,
    .length  = NFIRST_PRIMES,
    .data    = (uint32_t*)first_primes
}};
"""

HEADER = """\
{license}
/**
 * \\file    {name_inc}
 * \\author  Automatically generated by {name_prog}
 * \\date    {date}
 * \\version {version}
 *
 * \\brief Precomputed small primes.
 *
 * This is a list of the precomputed small primes together with
 * a \\c uint32_array_t wrapper.
 */

#if !defined({guard})
   /**
    * \\def {guard}
    * Standard include guard.
    */
#define {guard}

#include <inttypes.h>

#include "array.h"
#include "tifa_config.h"

/**
 * \\def NFIRST_PRIMES
 * Number of precomputed primes in the \\c first_primes array.
 */
#define NFIRST_PRIMES {nprimes}

/**
 * The \\c first_primes array is a global array of \\c uint32_t elements
 * containing the first \\c NFIRST_PRIMES prime numbers (from 2 and beyond).
 */
extern TIFA_API const uint32_t first_primes[NFIRST_PRIMES] MAYBE_UNUSED;

/**
 * The largest prime in the \\c first_primes array.
 */
extern TIFA_API const uint32_t LARGEST_PRIME MAYBE_UNUSED;

/**
 * \\c first_primes_array is a \\c uint32_array_t wrapper to the array
 * \\c first_primes.
 *
 * \\note \\c first_primes_array 's \\c alloced field is set to zero. Indeed,
 * \\c first_primes_array is merely a \\c uint32_array_t wrapper for
 * \\c first_primes, and as such, it has no real "alloced" memory. Setting
 * \\c first_primes_array.alloced to 0 will prevent errors
 * if \\c free_uint32_array is inadvertently called on \\c first_primes_array.
 */
extern TIFA_API const uint32_array_t first_primes_array MAYBE_UNUSED;

#endif

"""


def smallest_primes(count):
    # The count-th prime is below n.(ln n + ln ln n) from n = 6 on.
    bound = 15 if count < 6 else int(count * (log(count) + log(log(count)))) + 1
    sieve = bytearray([1]) * (bound + 1)
    sieve[0:2] = b"\0\0"
    for p in range(2, int(bound ** 0.5) + 1):
        if sieve[p]:
            sieve[p * p::p] = bytes(len(range(p * p, bound + 1, p)))
    return [p for p in range(bound + 1) if sieve[p]][:count]


def main():
    parser = argparse.ArgumentParser(
        description="Writes the smallest primes as a C header and source file "
                    "(PREFIX.h and PREFIX.c).")
    parser.add_argument("--out", required=True, metavar="PREFIX",
                        help="output file prefix: PREFIX.h and PREFIX.c")
    parser.add_argument("--nprimes", type=int, default=65536,
                        help="number of primes (default: 65536)")
    parser.add_argument("--date", type=datetime.date.fromisoformat,
                        default=datetime.date.today(), metavar="YYYY-MM-DD",
                        help="date in the files' comments (default: today)")
    parser.add_argument("--force", action="store_true",
                        help="overwrite the output files if they exist")
    args = parser.parse_args()

    if not 1 <= args.nprimes <= NMAX_PRIMES:
        sys.exit(f"Error: the number of primes must be in [1, {NMAX_PRIMES}]")
    output_inc = args.out + ".h"
    output_src = args.out + ".c"
    for path in (output_inc, output_src):
        if os.path.exists(path) and not args.force:
            sys.exit(f"Error: output file {path} already exists "
                     "(--force overwrites it)")

    primes = smallest_primes(args.nprimes)
    fields = {
        "license":   LICENSE,
        "name_prog": os.path.basename(sys.argv[0]),
        "name_inc":  os.path.basename(output_inc),
        "name_src":  os.path.basename(output_src),
        "date":      args.date.strftime("%a %b %d %Y"),
        "version":   args.date.isoformat(),
        "nprimes":   args.nprimes,
        "largest":   primes[-1],
        "rows":      ",\n".join(f"\t{p}" for p in primes),
        "guard":     "_TIFA_" + re.sub(r"\W", "_",
                                       os.path.basename(args.out).upper())
                     + "_H_",
    }
    with open(output_src, "w", newline="\n") as f:
        f.write(SOURCE.format(**fields))
    with open(output_inc, "w", newline="\n") as f:
        f.write(HEADER.format(**fields))
    print(f"{args.nprimes} primes written to {output_inc} and {output_src}")


if __name__ == "__main__":
    main()
